"""Generate the ggml codebook tables Infernix decodes GGUF i-quants with.

The tables (grids, sign patterns, the IQ4_NL values) are data of the GGUF formats themselves,
defined in llama.cpp's ``ggml/src/ggml-common.h`` (MIT). This script copies them verbatim from a
local copy of that header into two committed outputs: ``ggml_tables.py`` (the Python codecs and
their oracles) and ``src/ops/ggml/ggml_tables.h`` (the CUDA and CPU kernels).

    python -m tools.artifact.codecs.generate_ggml_tables PATH/TO/ggml-common.h
"""

from __future__ import annotations

import argparse
from pathlib import Path
import re

TABLES = (
    ("kmask_iq2xs", "uint8_t", 8),
    ("ksigns_iq2xs", "uint8_t", 128),
    ("iq2s_grid", "uint64_t", 1024),
    ("iq3xxs_grid", "uint32_t", 256),
    ("iq3s_grid", "uint32_t", 512),
    ("kvalues_iq4nl", "int8_t", 16),
)

_ROOT = Path(__file__).resolve().parents[3]


def read_tables(header: Path) -> dict[str, list[int]]:
    text = header.read_text(encoding="utf-8")
    out = {}
    for name, ctype, size in TABLES:
        match = re.search(
            r"GGML_TABLE_BEGIN\(\s*" + re.escape(ctype) + r"\s*,\s*" + re.escape(name) + r"\s*,\s*(\d+)\s*\)(.*?)GGML_TABLE_END\(\)",
            text,
            re.S,
        )
        if match is None:
            raise ValueError(f"{header}: table {name} not found")
        if int(match.group(1)) != size:
            raise ValueError(f"{name}: expected {size} entries, header declares {match.group(1)}")
        body = re.sub(r"//[^\n]*", "", match.group(2))
        values = [int(token, 0) for token in re.findall(r"-?(?:0x[0-9a-fA-F]+|\d+)", body)]
        if len(values) != size:
            raise ValueError(f"{name}: parsed {len(values)} values, expected {size}")
        out[name] = values
    return out


def python_module(tables: dict[str, list[int]], source: str) -> str:
    lines = [
        '"""ggml codebook tables, copied verbatim from llama.cpp ggml-common.h (MIT).',
        "",
        f"Generated by tools.artifact.codecs.generate_ggml_tables from {source}; do not edit.",
        '"""',
        "",
    ]
    for name, ctype, _ in TABLES:
        values = tables[name]
        width = 4 if ctype == "uint64_t" else 8 if ctype == "uint32_t" else 16
        fmt = (lambda v: f"0x{v:016x}") if ctype == "uint64_t" else (lambda v: f"0x{v:08x}") if ctype == "uint32_t" else str
        lines.append(f"{name.upper()} = (")
        for i in range(0, len(values), width):
            lines.append("    " + ", ".join(fmt(v) for v in values[i : i + width]) + ",")
        lines.append(")")
        lines.append("")
    return "\n".join(lines)


def cpp_header(tables: dict[str, list[int]], source: str) -> str:
    lines = [
        "#pragma once",
        "",
        "// ggml codebook tables, copied verbatim from llama.cpp ggml-common.h (MIT, see",
        "// packaging/windows/THIRD_PARTY_NOTICES.md). Generated by",
        f"// tools/artifact/codecs/generate_ggml_tables.py from {source}; do not edit.",
        "",
        "#include <cstdint>",
        "",
        "namespace infernix::ggml {",
        "",
    ]
    for name, ctype, size in TABLES:
        values = tables[name]
        width = 4 if ctype == "uint64_t" else 8 if ctype == "uint32_t" else 16
        fmt = (lambda v: f"0x{v:016x}ULL") if ctype == "uint64_t" else (lambda v: f"0x{v:08x}U") if ctype == "uint32_t" else str
        lines.append(f"inline constexpr std::{ctype} k_{name}[{size}] = {{")
        for i in range(0, len(values), width):
            lines.append("    " + ", ".join(fmt(v) for v in values[i : i + width]) + ",")
        lines.append("};")
        lines.append("")
    lines.append("} // namespace infernix::ggml")
    lines.append("")
    return "\n".join(lines)


def cuda_header(tables: dict[str, list[int]], source: str) -> str:
    lines = [
        "#pragma once",
        "",
        "// Device copies of the ggml codebook tables (ggml_tables.h), one per translation unit (static",
        "// module data, no allocation). Generated by tools/artifact/codecs/generate_ggml_tables.py from",
        f"// {source}; do not edit.",
        "",
        "#include <cstdint>",
        "",
        "namespace infernix::ggml {",
        "",
    ]
    for name, ctype, size in TABLES:
        values = tables[name]
        width = 4 if ctype == "uint64_t" else 8 if ctype == "uint32_t" else 16
        fmt = (lambda v: f"0x{v:016x}ULL") if ctype == "uint64_t" else (lambda v: f"0x{v:08x}U") if ctype == "uint32_t" else str
        lines.append(f"static __device__ const std::{ctype} d_{name}[{size}] = {{")
        for i in range(0, len(values), width):
            lines.append("    " + ", ".join(fmt(v) for v in values[i : i + width]) + ",")
        lines.append("};")
        lines.append("")
    lines.append("} // namespace infernix::ggml")
    lines.append("")
    return "\n".join(lines)


def main(argv=None) -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("header", type=Path, help="llama.cpp ggml/src/ggml-common.h")
    args = parser.parse_args(argv)
    tables = read_tables(args.header)
    source = "llama.cpp ggml/src/ggml-common.h"
    (Path(__file__).with_name("ggml_tables.py")).write_text(python_module(tables, source), encoding="utf-8", newline="\n")
    target = _ROOT / "src" / "ops" / "ggml" / "ggml_tables.h"
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(cpp_header(tables, source), encoding="utf-8", newline="\n")
    device = target.with_name("ggml_tables_device.cuh")
    device.write_text(cuda_header(tables, source), encoding="utf-8", newline="\n")
    print(f"wrote {Path(__file__).with_name('ggml_tables.py')}, {target} and {device}")


if __name__ == "__main__":
    main()
