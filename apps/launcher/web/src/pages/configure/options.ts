// The launch-parameter form's sections and the infernix-serve option each control edits. Every
// option of `infernix-serve --help` has a control here, is set by the launcher itself
// (LAUNCHER_FLAGS) or has one of the page's own fields (the sections' `fields`):
// tests/test_launcher_option_coverage.py checks that against src/serve/serve_options.cpp, so an
// option added to the server is noticed here. It reads this file as text: each control starts
// with its `kind`, then its `flag`. A control with `more` sits under its section's "More options".

